    // Legitimate external signing configuration only when explicit environment secrets exist.
    // Never embeds or fabricates a private release keystore inside the repository.
    val keystorePath = System.getenv("CALLORA_KEYSTORE_PATH")
    val keystorePassword = System.getenv("CALLORA_KEYSTORE_PASSWORD")
    val keyAlias = System.getenv("CALLORA_KEY_ALIAS")
    val keyPassword = System.getenv("CALLORA_KEY_PASSWORD")
    val hasReleaseSigning = !keystorePath.isNullOrBlank() &&
        !keystorePassword.isNullOrBlank() &&
        !keyAlias.isNullOrBlank() &&
        !keyPassword.isNullOrBlank() &&
        file(keystorePath).exists()

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = file(keystorePath!!)
                storePassword = keystorePassword
                this.keyAlias = keyAlias
                this.keyPassword = keyPassword
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
